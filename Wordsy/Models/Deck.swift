import Foundation
import SwiftData

@Model
final class Deck {
    var id: UUID
    var title: String
    var createdAt: Date
    var lastOpenedAt: Date
    var isPublic: Bool
    
    @Relationship(deleteRule: .cascade, inverse: \Card.deck)
    var cards: [Card]
    
    var folder: Folder?
    
    init(title: String, cards: [Card], lastOpenedAt: Date, isPublic: Bool) {
        self.id = UUID()
        self.title = title
        self.createdAt = .now
        self.cards = cards
        self.lastOpenedAt = lastOpenedAt
        self.isPublic = isPublic
    }
}

/*
Разберём @Relationship подробно — это действительно не самая очевидная часть SwiftData.

Что такое связь между Deck и Card концептуально. Это ровно то же самое, что "внешний ключ" в обычной базе данных: у одной колоды много карточек, у одной карточки — одна колода-родитель. Deck.cards — это "мои дети", Card.deck — это "мой родитель". По сути одна и та же связь, просто описанная с двух сторон.

Зачем нужны обе стороны, а не только Deck.cards. Практическая причина: представь сессию изучения, где карточки идут вперемешку из разных колод (как раз наш кейс с "Освоить"/"Закрепить" на главном экране — там подборки смешанные). Если бы у Card не было deck, ты бы не смог, глядя на отдельную карточку, сказать "она из колоды Испанские глаголы" — некуда было бы посмотреть. card.deck?.title даёт этот путь назад.

Зачем нужен именно inverse: \Card.deck, а не просто два независимых свойства. Без inverse SwiftData видела бы Deck.cards и Card.deck как две не связанные друг с другом вещи — просто два массива/поля, которые случайно ссылаются на одинаковые типы. Ты мог бы записать карточку в deck.cards, а её card.deck осталась бы nil, и наоборот — данные разъехались бы. inverse: — это то, что говорит SwiftData "это не два свойства, это две стороны одной и той же связи, следи, чтобы они не расходились".

deleteRule: .cascade. Когда удаляют Deck, кто-то должен решить, что делать с его карточками. У SwiftData есть варианты: .cascade (удалить и карточки тоже — наш случай, осиротевшая карточка без колоды никому не нужна), .nullify (карточки останутся, но card.deck станет nil, это дефолт), .deny (запретить удаление колоды, пока в ней есть карточки). Мы выбрали .cascade — логично для нашего приложения. Обрати внимание, что правило висит только на стороне Deck.cards (на "родителе"), а не на Card.deck — это осмысленно, правило именно про "что будет с детьми", поэтому и живёт у родителя.
*/

/*
@Model, что вообще делает, — это макрос (появился в iOS 17 вместе со SwiftData), который превращает обычный Swift-класс в то, чем может управлять SwiftData. Конкретно он:

Регистрирует свойства как схему — как будто ты описываешь колонки таблицы в базе данных. SwiftData смотрит на все var-свойства класса и понимает "вот из чего состоит одна запись Card".

Делает класс наблюдаемым автоматически — похоже на то, что даёт @Published в ObservableObject, но тут не нужно расставлять аннотации на каждое поле руками. Если у тебя SwiftUI-view подписан на такой объект (через @Query, о котором говорили раньше), она сама обновится, когда поле объекта изменится.

Включает связи через @Relationship — та самая Deck.cards, которую мы обсуждали, с правилом каскадного удаления (deleteRule: .cascade) — удалил колоду, удалились и её карточки.

Требует именно class, а не struct — потому что SwiftData должно отслеживать "это та же самая запись в базе" даже после изменений, а это работает только через ссылочную идентичность объекта, не через копирование значений.
 */
