import Foundation

enum CardStatus: String, Codable, CaseIterable {
    case new, learning, learned
    
    var title: String {
        switch self {
        case .new:
            "Новые"
        case .learning:
            "Изучаю"
        case .learned:
            "Выучено"
        }
    }
}

/*
 enum — перечисление: тип, у которого заранее известен весь конечный список возможных значений. В отличие от String (где может быть любой текст), CardStatus может быть только одним из трёх: .new, .learning, .learned. Это сильнее, чем просто строка "new" — компилятор не даст тебе написать .neww с опечаткой или забыть обработать один из случаев в switch.

 После двоеточия — три протокола, через запятую. Разберём каждый:

 String — это "raw value" тип. Означает: у каждого case есть скрытое строковое представление. Раз явно не написано case new = "newValue", то по умолчанию Swift берёт имя самого case как строку: .new → "new", .learning → "learning", .learned → "learned". Можно это увидеть явно: CardStatus.new.rawValue == "new". Зачем это вообще нужно — смотри ниже про Codable.

 Codable — протокол, который даёт перечислению умение сериализоваться в JSON и обратно (encode/decode). Именно благодаря комбинации String + Codable значение .learning при сохранении куда-то (например, в JSON-файл или в сеть) превратится в текст "learning", а не в бессмысленное число вроде 1. Сейчас в проекте CardStatus нигде реально не кодируется в JSON (храним в памяти через SwiftData, а сам status у Card — вычисляемое свойство, не хранимое, поэтому оно вообще не участвует в сохранении SwiftData). То есть Codable тут — задел на будущее (например, если потом добавишь экспорт/импорт колод через JSON), а не то, что реально сейчас используется.

 CaseIterable — автоматически даёт статический массив CardStatus.allCases, который содержит [.new, .learning, .learned] в порядке объявления. Полезно, если понадобится, например, пройтись циклом по всем трём статусам (сейчас в коде нигде не используется, но тоже задел на будущее — например, если захочешь вывести три секции на экране).
 */
